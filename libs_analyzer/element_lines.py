def match_lines(peak_wavelength, tolerance_nm):
    """
    在元素谱线库中查找距离给定波长最近的谱线（误差 <= tolerance_nm）。

    返回按偏差升序排列的候选列表，每项:
        {"element", "name", "line", "rel", "delta"}
    """
    candidates = []
    for element, lines in ELEMENT_LINES.items():
        for line, rel in lines:
            delta = abs(line - peak_wavelength)
            if delta <= tolerance_nm:
                candidates.append({
                    "element": element,
                    "name": ELEMENT_NAMES.get(element, element),
                    "line": line,
                    "rel": rel,
                    "delta": delta,
                })
    candidates.sort(key=lambda c: c["delta"])
    return candidates


def all_lines_sorted():
    """返回全部谱线 (波长, 元素, 相对强度) 按波长排序，用于绘图参考。"""
    out = []
    for element, lines in ELEMENT_LINES.items():
        for line, rel in lines:
            out.append((line, element, rel))
    out.sort(key=lambda x: x[0])
    return out
